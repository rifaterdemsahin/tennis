const I18N_KEY = "clt-lang";

function currentLang() {
  const q = new URLSearchParams(location.search).get("lang");
  if (q && T[q]) return q;
  const saved = localStorage.getItem(I18N_KEY);
  if (saved && T[saved]) return saved;
  return "en";
}

function t(key) {
  const lang = document.documentElement.lang || "en";
  return (T[lang] && T[lang][key]) || T.en[key] || key;
}

function applyI18n(lang) {
  const dict = T[lang] || T.en;
  document.documentElement.lang = lang === "zh" ? "zh-Hans" : lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = dict[key] || T.en[key];
    if (val == null) return;
    if (el.hasAttribute("data-i18n-html")) el.innerHTML = val;
    else el.textContent = val;
  });
  document.querySelectorAll(".langbar button").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.dataset.lang === lang ? "true" : "false");
  });
  applyPlaceholders(lang);
  if (typeof window.renderCalendar === "function") window.renderCalendar();
}

function mountRepoFooter() {
  const foot = document.querySelector("footer") || document.body.appendChild(document.createElement("footer"));
  if (foot.querySelector(".repo-note")) return;
  const note = document.createElement("p");
  note.className = "repo-note";
  note.setAttribute("data-i18n", "repo_note");
  note.setAttribute("data-i18n-html", "");
  note.innerHTML = T.en.repo_note;
  foot.appendChild(note);
}

function mountLangBar() {
  if (document.querySelector(".langbar")) return;
  const bar = document.createElement("div");
  bar.className = "langbar";
  bar.setAttribute("role", "navigation");
  bar.setAttribute("aria-label", "Language");
  const label = document.createElement("span");
  label.className = "label";
  label.setAttribute("data-i18n", "translate");
  label.textContent = "Translate";
  bar.appendChild(label);
  LANGS.forEach((l) => {
    const b = document.createElement("button");
    b.type = "button";
    b.dataset.lang = l.id;
    b.textContent = `${l.flag} ${l.label}`;
    b.addEventListener("click", () => {
      localStorage.setItem(I18N_KEY, l.id);
      const url = new URL(location.href);
      url.searchParams.set("lang", l.id);
      history.replaceState(null, "", url);
      applyI18n(l.id);
    });
    bar.appendChild(b);
  });
  const searchWrap = document.createElement("div");
  searchWrap.className = "site-search";
  searchWrap.innerHTML = `<input type="search" data-i18n-placeholder="search_ph" placeholder="Search this site" aria-label="Search this site"><div class="hits" role="listbox"></div>`;
  bar.appendChild(searchWrap);
  document.body.insertBefore(bar, document.body.firstChild);
  wireSearch(searchWrap);
}

